#!/usr/bin/env python3
# File: controller/landscapes/statuspage_landscape.py
# Purpose: REQ-GHA-036 — build an outside-view landscape file for a public system only from
#   what its provider publishes (its public status page's component list). No part is invented.
# Usage: statuspage_landscape.py <summary.json url> <product> <prefix> > <product>.yaml
#   e.g. statuspage_landscape.py https://www.cloudflarestatus.com/api/v2/summary.json cloudflare cf

import json
import re
import sys
import urllib.request

import yaml

USER_AGENT = "GlassHood-monitor/1.0 (+https://glasshood.ai; read-only status check)"


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:60]


def build(summary: dict, url: str, product: str, prefix: str) -> dict:
    page = summary.get("page") or {}
    comps = summary.get("components") or []
    groups = {c["id"]: c for c in comps if c.get("group")}
    members: dict = {}
    for c in comps:
        if c.get("group") or (c.get("name") or "").lower().startswith("visit "):
            continue  # a group header is the group itself; "Visit … for more information" is a link
        members.setdefault(c.get("group_id") or "_top", []).append(c)
    order = sorted(members, key=lambda g: (g == "_top" and 0 or 1, -len(members[g])))
    out_groups, nodes, used = [], [], set()
    for i, gid in enumerate(order):
        name = "Services" if gid == "_top" else groups[gid]["name"]
        gname = slug(name) or f"g{i}"
        items = sorted(members[gid], key=lambda c: c.get("position") or 0)
        cols = 8 if len(items) > 40 else (6 if len(items) > 12 else 4)
        ids = []
        for c in items:
            nid = f"{prefix}-{slug(c['name'])}"
            while nid in used:
                nid += "-x"
            used.add(nid)
            ids.append(nid)
            nodes.append({"id": nid, "label": c["name"], "type": "provider",
                          "monitoring": {"probe": {"type": "statuspage", "url": url, "component_id": c["id"]}}})
        out_groups.append({"name": gname, "label": f"{name} ({len(items)})", "style": "default",
                           "order": i, "row": i // 2, "col": i % 2, "columns": cols, "nodes": ids})
    return {
        "schema_version": 2, "company": "", "kind": "outside_view",
        "solution": page.get("name", product).replace(" Status", "").strip() or product,
        "product": product, "project_id": "", "region": "",
        "source": page.get("url", ""),
        "environments": [{"environment": "public",
                          "display_name": f"Outside view: built from what {page.get('name', product)} publishes",
                          "order": 10, "groups": out_groups, "nodes": nodes, "edges": []}],
    }


def main():
    url, product, prefix = sys.argv[1:4]
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    summary = json.load(urllib.request.urlopen(req, timeout=20))
    head = (f"# File: config/manifests/{product}.yaml (kept outside the repo, like every landscape)\n"
            f"# Purpose: REQ-GHA-036 outside view of {summary.get('page', {}).get('name', product)}, generated by\n"
            f"#   controller/landscapes/statuspage_landscape.py from the provider's published components only.\n")
    sys.stdout.write(head + yaml.safe_dump(build(summary, url, product, prefix), sort_keys=False, allow_unicode=True))


if __name__ == "__main__":
    main()
